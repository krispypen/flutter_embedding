import 'dart:io';

/// Installs a Gradle user init script that disables Javadoc (Dokka) generation
/// during `flutter build aar` builds.
///
/// The Flutter SDK's `aar_init_script.gradle` unconditionally configures
/// `withJavadocJar()` for every published AAR variant. The Dokka-based
/// `javaDoc<Variant>Generation` tasks are slow and fail intermittently on CI,
/// and the javadoc jars are not needed for the embedding SDK.
///
/// Only the `*Generation` tasks are disabled: the `javaDoc<Variant>Jar` tasks
/// still run (producing empty jars), so the Maven publications stay valid.
/// The script is guarded on `assembleAar*` task names, so other Android builds
/// on the same machine are unaffected.
Future<void> ensureAarJavadocDisabled(bool verbose) async {
  final home = Platform.environment['HOME'] ?? Platform.environment['USERPROFILE'];
  final gradleUserHome = Platform.environment['GRADLE_USER_HOME'] ?? (home != null ? '$home/.gradle' : null);
  if (gradleUserHome == null) {
    return;
  }

  const content = '''
// Generated by flutter_embedding_cli. Safe to delete.
// Disables Javadoc (Dokka) generation during `flutter build aar`: the javadoc
// jars are not needed for the embedding SDK, the Dokka tasks fail
// intermittently on CI, and skipping them saves build time. Only applies to
// Gradle invocations that run assembleAar* tasks; other builds are unaffected.
def isFlutterAarBuild = gradle.startParameter.taskNames.any { it.contains('assembleAar') }
if (isFlutterAarBuild) {
    allprojects {
        // configureEach (not whenTaskAdded): the eager API forces early task
        // realization, which breaks AGP's lazy build service registration
        tasks.configureEach { task ->
            if (task.name.startsWith('javaDoc') && task.name.endsWith('Generation')) {
                task.enabled = false
            }
        }
    }
}
''';

  final script = File('$gradleUserHome/init.d/flutter_embedding_disable_aar_javadoc.gradle');
  if (!script.existsSync() || script.readAsStringSync() != content) {
    script.parent.createSync(recursive: true);
    script.writeAsStringSync(content);
  }
  print('AAR javadoc (Dokka) generation disabled via Gradle init script: ${script.path}');
}
