import 'dart:io';

import 'package:path/path.dart';

/// The name of the generated Swift package and its library product.
///
/// Kept in sync with the CocoaPods pod name in generate_pod_spec.dart so both
/// integrations expose the SDK under the same name.
const spmPackageName = 'FlutterEmbeddingModule';

/// Generates a local Swift Package Manager package in [packageDirectory].
///
/// Expects the hybrid xcframeworks to already be present in
/// [packageDirectory]/Frameworks (see generateHybridXcframeworks). Writes a
/// Package.swift with one binary target per xcframework plus a wrapper target
/// that links them all into a single library product, so a host app only has
/// to add the package and depend on one product.
Future<void> generateSpmPackage(Directory packageDirectory) async {
  final frameworksDirectory = Directory(join(packageDirectory.path, 'Frameworks'));
  if (!frameworksDirectory.existsSync()) {
    throw Exception('Failed to find ${frameworksDirectory.path}, '
        'make sure generateHybridXcframeworks ran first.');
  }

  final frameworkNames = frameworksDirectory
      .listSync(followLinks: false)
      .whereType<Directory>()
      .where((entity) => entity.path.endsWith('.xcframework'))
      .map((entity) => basenameWithoutExtension(entity.path))
      .toList()
    ..sort();
  if (frameworkNames.isEmpty) {
    throw Exception('No xcframeworks found in ${frameworksDirectory.path}.');
  }
  if (frameworkNames.contains(spmPackageName)) {
    throw Exception('An xcframework is named $spmPackageName, '
        'which collides with the generated Swift package wrapper target.');
  }

  // The wrapper target needs at least one source file to compile; the public
  // API lives in the binary frameworks, not here.
  final registrantReference = frameworkNames.contains('FlutterPluginRegistrant')
      ? '''
import FlutterPluginRegistrant

/// flutter_embedding looks up GeneratedPluginRegistrant with NSClassFromString,
/// so nothing references the class at link time. FlutterPluginRegistrant is a
/// static framework, which means the linker would dead-strip the class without
/// this hard reference and plugin registration would silently be skipped
/// (CocoaPods avoids that with the -ObjC linker flag instead).
public let flutterEmbeddingPluginRegistrant: AnyClass = GeneratedPluginRegistrant.self
'''
      : '';
  final sourcesDirectory = Directory(join(packageDirectory.path, 'Sources', spmPackageName));
  sourcesDirectory.createSync(recursive: true);
  File(join(sourcesDirectory.path, '$spmPackageName.swift')).writeAsStringSync('''
// Generated by flutter_embedding_cli. Do not edit.
//
// This target only exists so the $spmPackageName library product links and
// embeds all vendored Flutter xcframeworks. Import the frameworks you need
// directly (e.g. `import flutter_embedding`).
$registrantReference''');

  final binaryTargets = frameworkNames
      .map((name) => '''
        .binaryTarget(
            name: "$name",
            path: "Frameworks/$name.xcframework"
        ),''')
      .join('\n');
  final wrapperDependencies = frameworkNames.map((name) => '                .target(name: "$name"),').join('\n');

  File(join(packageDirectory.path, 'Package.swift')).writeAsStringSync('''
// swift-tools-version:5.9
// Generated by flutter_embedding_cli. Do not edit.
//
// The xcframeworks in Frameworks/ are hybrids: their device slice is the
// Release (AOT) build and their simulator slice is the Debug (JIT) build, so
// this single package works on physical devices and simulators regardless of
// the host app's build configuration. Note that Flutter code therefore runs
// in debug mode on simulators (slower, Dart asserts enabled).
import PackageDescription

let package = Package(
    name: "$spmPackageName",
    platforms: [
        .iOS(.v13),
    ],
    products: [
        .library(
            name: "$spmPackageName",
            targets: ["$spmPackageName"]
        ),
    ],
    targets: [
        .target(
            name: "$spmPackageName",
            dependencies: [
$wrapperDependencies
            ]
        ),
$binaryTargets
    ]
)
''');

  File(join(packageDirectory.path, 'README.md')).writeAsStringSync('''
# $spmPackageName

Generated by flutter_embedding_cli. Do not edit.

A local Swift package that embeds the Flutter module into a native iOS app.

## Integration

1. In Xcode: File > Add Package Dependencies... > Add Local... and select this
   directory (or drag this directory into your project navigator).
2. Add the `$spmPackageName` library to your app target
   (General > Frameworks, Libraries, and Embedded Content).

## Notes

- The xcframeworks are hybrids: physical devices run the Release (AOT) build,
  simulators run the Debug (JIT) build. Flutter screens are therefore slower
  on simulators than on devices, independent of your build configuration.
- Do not add these frameworks through CocoaPods as well; pick one integration.
''');

  print('Swift package generated in: ${packageDirectory.path}');
}
